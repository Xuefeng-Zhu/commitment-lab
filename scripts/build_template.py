#!/usr/bin/env python3
"""Build the standalone Switch Console template from the editable lab materials."""

from pathlib import Path
import argparse
import sys
import textwrap

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "commitment-lab.template.yaml"


def block(path: str, spaces: int) -> str:
    value = (ROOT / path).read_text(encoding="utf-8").strip()
    return textwrap.indent(value, " " * spaces)


def render() -> str:
    stakeholder = block("lab/stakeholder-instructions.md", 6)
    coach = block("lab/coach-instructions.md", 6)
    return f'''# Generated by scripts/build_template.py. Edit lab/* and regenerate.
# Agent instructions are embedded because Switch creates separate agent directories.
version: 1
params:
  team:
    type: string
    description: Short lowercase prefix for the room and agent names
    default: commitment
    pattern: "[a-z][a-z0-9-]*"
  provider:
    type: provider
    description: Installed and authenticated coding agent used for both participants
    default: [codex, claude, opencode]
    input: advanced
  location:
    type: location
    description: Machine where the agents run
    default: local
    input: advanced
  directory:
    type: directory
    description: Parent directory for separate per-agent working directories
    default: "{{$agents_dir}}"
    input: advanced
  bridge:
    type: bridge
    description: Messaging app in which to create the practice room
    default: [$first]

agents:
  - name: "{{team}}-stakeholder"
    description: Sales stakeholder in a fictional launch negotiation
    addressing: anyone
    provider: "{{provider}}"
    location: "{{location}}"
    directory: "{{directory}}/{{agent}}"
    instructions: |
{stakeholder}
  - name: "{{team}}-coach"
    description: Gives transcript-grounded feedback after a practice round
    addressing: anyone
    provider: "{{provider}}"
    location: "{{location}}"
    directory: "{{directory}}/{{agent}}"
    instructions: |
{coach}

room:
  name: "{{team}}-lab"
  description: Fictional launch-commitment practice with a learner, a human mentor and two agents
  channel_type: channel_private
  read_visibility: private
  write_visibility: private
  instructions: |
    This is a fictional training exercise. The room creator is the learner,
    and a human mentor plays engineering. The stakeholder plays Sales and
    the coach debriefs only when asked. Address an agent by its actual name
    to request a response. The mentor contributes feasibility independently;
    do not impersonate them or invent customer agreement. Label missing facts
    as unknown. No messages or actions outside this room are part of the exercise.
  bridge: "{{bridge}}"
  agents: ["{{team}}-stakeholder", "{{team}}-coach"]
  users: ["{{$creator}}"]

kickoff: |
  @{{team}}-stakeholder: please open the fictional Friday launch exercise in
  one short message. Learner: ask questions, consult the human mentor playing
  engineering, and propose a plan. When ready, address the coach named
  {{team}}-coach for a debrief. Add a mentor to the room separately; if
  role-playing the mentor, clearly identify those messages as simulated.
'''


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the generated template is stale")
    args = parser.parse_args()
    expected = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != expected:
            print("Template is stale; run python3 scripts/build_template.py", file=sys.stderr)
            return 1
        print("Template matches lab instructions.")
        return 0
    OUTPUT.write_text(expected, encoding="utf-8")
    print(f"Wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
